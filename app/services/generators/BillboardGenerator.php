<?php
// app/services/generators/BillboardGenerator.php — generate BillboardGui di atas kepala player
// Input: nodes hasil convert + nama player / role / level
// Output: Lua script siap paste

class BillboardGenerator {

    /**
     * Generate script BillboardGui overhead
     *
     * @param array $config {
     *   name: string,
     *   role: string,
     *   level: int,
     *   offsetY: float (default 3.5),
     *   size: [w, h] (default [200, 60]),
     *   maxDistance: int (default 100),
     *   theme: 'gold' | 'blue' | 'purple'
     * }
     */
    public static function generate($config = []) {
        $name        = $config['name']        ?? 'Player';
        $role        = $config['role']        ?? 'Member';
        $level       = (int)($config['level'] ?? 1);
        $offsetY     = (float)($config['offsetY'] ?? 3.5);
        $width       = (int)($config['size'][0] ?? 220);
        $height      = (int)($config['size'][1] ?? 70);
        $maxDistance = (int)($config['maxDistance'] ?? 120);
        $theme       = $config['theme']       ?? 'gold';

